-- Synthetic records only; does not send email. Every fixture rolls back.
begin;
create temporary table invite_ctx(k text primary key,id uuid not null default gen_random_uuid());
insert into invite_ctx(k) values('manager'),('member'),('outsider'),('unverified'),('org'),('paused');
grant select on invite_ctx to authenticated,anon,service_role;
create temporary table invite_result(data jsonb);
grant select,insert,update on invite_result to authenticated,service_role;
insert into auth.users(id,email,email_confirmed_at,is_anonymous)
select id,'invite-check-'||id||'@example.invalid',case when k='unverified' then null else now() end,false from invite_ctx where k in ('manager','member','outsider','unverified');
insert into public.staff_members(user_id,role,active) select id,'manager',true from invite_ctx where k in ('manager','unverified');
insert into public.star_organisations(id,name,kind,active,created_by) select id,'Synthetic invite check','school',k='org',(select id from invite_ctx where k='manager') from invite_ctx where k in ('org','paused');
create function pg_temp.check_it(ok boolean,message text) returns void language plpgsql as $$begin if ok is distinct from true then raise exception 'Invitation check failed: %',message; end if; end$$;
create function pg_temp.invite_data() returns jsonb language sql as $$ select jsonb_build_object('organisation_id',(select id from invite_ctx where k='org'),'email','  INVITE-CHECK-'||(select id from invite_ctx where k='member')||'@EXAMPLE.INVALID  ','name','Synthetic teacher') $$;
create function pg_temp.prepare_denied(payload jsonb,expected text) returns void language plpgsql as $$
begin
 begin perform public.star_prepare_organisation_invitation(payload);
 exception when others then if position(expected in sqlerrm)>0 then return; else raise; end if; end;
 raise exception 'Expected rejection: %',expected;
end $$;
set local role authenticated;
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='outsider'),true);
select pg_temp.prepare_denied(pg_temp.invite_data(),'management access');
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='unverified'),true);
select pg_temp.prepare_denied(pg_temp.invite_data(),'management access');
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='manager'),true);
select pg_temp.prepare_denied(pg_temp.invite_data()||jsonb_build_object('organisation_id',(select id from invite_ctx where k='paused')),'active organisation');
select pg_temp.prepare_denied(pg_temp.invite_data()||'{"email":"bad address"}','valid email');
insert into invite_result select public.star_prepare_organisation_invitation(pg_temp.invite_data());
select pg_temp.check_it((select (data->>'existing_account')::boolean from invite_result),'confirmed existing account detected');
select pg_temp.check_it((select data->>'email'='invite-check-'||(select id from invite_ctx where k='member')||'@example.invalid' from invite_result),'email normalised');
select pg_temp.prepare_denied(pg_temp.invite_data(),'60 seconds');
select pg_temp.check_it(not has_function_privilege('authenticated','public.star_finish_organisation_invitation(uuid,uuid,boolean)','execute'),'client cannot forge sent status');
select pg_temp.check_it(not has_function_privilege('anon','public.star_prepare_organisation_invitation(jsonb)','execute'),'anonymous cannot prepare invites');
reset role;
set local role service_role;
select public.star_finish_organisation_invitation((data->>'id')::uuid,(data->>'attempt_id')::uuid,false) from invite_result;
reset role;
select pg_temp.check_it((select email_status='failed' and email_sent_at is null from public.star_organisation_members where id=(select (data->>'id')::uuid from invite_result)),'failed email is not reported sent');
set local role service_role;
select public.star_finish_organisation_invitation((data->>'id')::uuid,gen_random_uuid(),true) from invite_result;
reset role;
select pg_temp.check_it((select email_status='failed' from public.star_organisation_members where id=(select (data->>'id')::uuid from invite_result)),'stale attempt cannot overwrite status');
update public.star_organisation_members set email_attempted_at=now()-interval '2 minutes',expires_at=now()-interval '1 second' where id=(select (data->>'id')::uuid from invite_result);
set local role authenticated;
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='member'),true);
select public.star_organisation_portal('accept');
select pg_temp.check_it(jsonb_array_length(public.star_organisation_portal('workspace')->'organisations')=0,'expired invitation cannot grant access');
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='manager'),true);
update invite_result set data=public.star_prepare_organisation_invitation(pg_temp.invite_data());
reset role;
set local role service_role;
select public.star_finish_organisation_invitation((data->>'id')::uuid,(data->>'attempt_id')::uuid,true) from invite_result;
reset role;
select pg_temp.check_it((select email_status='sent' and email_sent_at is not null and expires_at>now() from public.star_organisation_members where id=(select (data->>'id')::uuid from invite_result)),'renewal and successful send recorded');
set local role authenticated;
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='member'),true);
select public.star_organisation_portal('accept');
select pg_temp.check_it(jsonb_array_length(public.star_organisation_portal('workspace')->'organisations')=1,'verified invited account gets its organisation');
select pg_temp.check_it((select count(*)=0 from public.staff_members),'organisation access does not grant internal staff access');
select pg_temp.prepare_denied(pg_temp.invite_data(),'management access');
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='manager'),true);
select pg_temp.prepare_denied(pg_temp.invite_data(),'already been accepted');
select public.star_organisation_portal('revoke_member',jsonb_build_object('id',(select data->>'id' from invite_result)));
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='member'),true);
select public.star_organisation_portal('accept');
select pg_temp.check_it(jsonb_array_length(public.star_organisation_portal('workspace')->'organisations')=0,'revoked access stays revoked after repeat acceptance');
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='manager'),true);
select public.star_organisation_portal('restore_member',jsonb_build_object('id',(select data->>'id' from invite_result)));
select set_config('request.jwt.claim.sub',(select id::text from invite_ctx where k='member'),true);
select pg_temp.check_it(jsonb_array_length(public.star_organisation_portal('workspace')->'organisations')=1,'explicit manager restoration works');
reset role;
rollback;
select 'Invitation security checks passed; every synthetic fixture rolled back; no email sent.' as result;
